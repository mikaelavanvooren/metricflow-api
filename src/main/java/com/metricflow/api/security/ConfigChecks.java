package com.metricflow.api.security;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * The configuration and hygiene rules applied on every scan.
 *
 * <p>These complement the dependency scan: an artifact can be free of published advisories and
 * still be deployed in a way that is unsafe. Every rule reads resolved configuration only, so
 * nothing here parses source code.
 */
public final class ConfigChecks {

    /** Class file major version 61, that is Java 17, the oldest release still receiving updates. */
    static final int MINIMUM_BYTECODE_MAJOR = 61;

    private static final String HTTP_SECURITY_CLASS =
            "org.springframework.security.config.annotation.web.builders.HttpSecurity";

    private ConfigChecks() {
    }

    public static List<ConfigCheck> all() {
        return Collections.unmodifiableList(Arrays.asList(
                springBootSupported(),
                springSecurityPresent(),
                javaBaseline(),
                schemaNotAutoGenerated(),
                apiDocsProtected(),
                h2ConsoleDisabled()));
    }

    public static List<ConfigFinding> evaluateAll(ConfigCheckContext context) {
        List<ConfigFinding> findings = new ArrayList<>();
        for (ConfigCheck check : all()) {
            findings.add(check.evaluate(context));
        }
        return Collections.unmodifiableList(findings);
    }

    /**
     * Spring Boot 2.7 reached end of OSS support on 2023-11-24 and 3.0 on 2023-11-24 as well;
     * anything below 3.1 receives no free security patches, so new CVEs are never fixed for it.
     */
    static ConfigCheck springBootSupported() {
        return new AbstractCheck("spring-boot-supported", "Spring Boot receives security patches") {
            @Override
            public ConfigFinding evaluate(ConfigCheckContext context) {
                String version = context.getSpringBootVersion();
                if (version == null) {
                    return ConfigFinding.failing(getId(), getTitle(), Severity.UNKNOWN,
                            "Could not determine the Spring Boot version.",
                            "Verify the spring-boot-starter-parent version in pom.xml.");
                }
                int major = majorOf(version);
                int minor = minorOf(version);
                boolean unsupported = major < 3 || (major == 3 && minor < 1);
                if (unsupported) {
                    return ConfigFinding.failing(getId(), getTitle(), Severity.HIGH,
                            "Spring Boot " + version + " is past end of OSS support, so newly "
                                    + "published CVEs in the framework will never be patched on this line.",
                            "Upgrade to a supported Spring Boot line.");
                }
                return ConfigFinding.passing(getId(), getTitle(),
                        "Spring Boot " + version + " is on a supported line.");
            }
        };
    }

    /**
     * Without Spring Security every endpoint is anonymous, including the ones that enumerate this
     * application's own unpatched advisories.
     */
    static ConfigCheck springSecurityPresent() {
        return new AbstractCheck("spring-security-present", "Endpoints can be authenticated") {
            @Override
            public ConfigFinding evaluate(ConfigCheckContext context) {
                if (context.isClassPresent(HTTP_SECURITY_CLASS)) {
                    return ConfigFinding.passing(getId(), getTitle(),
                            "Spring Security is on the classpath.");
                }
                return ConfigFinding.failing(getId(), getTitle(), Severity.HIGH,
                        "Spring Security is not on the classpath, so every endpoint is served "
                                + "anonymously and no authorisation rules can be applied.",
                        "Add spring-boot-starter-security and restrict the non-public paths.");
            }
        };
    }

    static ConfigCheck javaBaseline() {
        return new AbstractCheck("java-baseline", "Compiled against a maintained Java release") {
            @Override
            public ConfigFinding evaluate(ConfigCheckContext context) {
                int major = context.getBytecodeMajorVersion();
                if (major <= 0) {
                    return ConfigFinding.failing(getId(), getTitle(), Severity.UNKNOWN,
                            "Could not read the application's class file version.",
                            "Verify the build produced class files.");
                }
                int release = ConfigCheckContext.javaFeatureRelease(major);
                if (major < MINIMUM_BYTECODE_MAJOR) {
                    return ConfigFinding.failing(getId(), getTitle(), Severity.MEDIUM,
                            "Application classes target Java " + release
                                    + ", which is behind the oldest Java release still receiving updates"
                                    + " and blocks upgrades to current framework versions.",
                            "Raise java.version to 17 or later.");
                }
                return ConfigFinding.passing(getId(), getTitle(),
                        "Application classes target Java " + release + ".");
            }
        };
    }

    /**
     * Letting Hibernate mutate the schema at boot means an application defect can silently alter or
     * drop production data.
     */
    static ConfigCheck schemaNotAutoGenerated() {
        return new AbstractCheck("jpa-ddl-auto", "Schema is not mutated at startup") {
            @Override
            public ConfigFinding evaluate(ConfigCheckContext context) {
                String mode = context.property("spring.jpa.hibernate.ddl-auto");
                String normalised = mode == null ? "none" : mode.trim().toLowerCase();
                boolean mutating = normalised.equals("update")
                        || normalised.equals("create")
                        || normalised.equals("create-drop");
                if (mutating && !context.isProfileActive("test")) {
                    return ConfigFinding.failing(getId(), getTitle(), Severity.MEDIUM,
                            "spring.jpa.hibernate.ddl-auto is '" + normalised
                                    + "', so Hibernate rewrites the schema on every startup.",
                            "Set ddl-auto to validate or none and manage the schema with migrations.");
                }
                return ConfigFinding.passing(getId(), getTitle(),
                        "spring.jpa.hibernate.ddl-auto is '" + normalised + "'.");
            }
        };
    }

    /** Published API documentation enumerates every route and payload shape for an attacker. */
    static ConfigCheck apiDocsProtected() {
        return new AbstractCheck("api-docs-protected", "API documentation is not public") {
            @Override
            public ConfigFinding evaluate(ConfigCheckContext context) {
                boolean uiEnabled = isEnabled(context, "springdoc.swagger-ui.enabled");
                boolean secured = context.isClassPresent(HTTP_SECURITY_CLASS);
                if (uiEnabled && !secured) {
                    return ConfigFinding.failing(getId(), getTitle(), Severity.MEDIUM,
                            "Swagger UI is enabled and no authentication is configured, so the full "
                                    + "API surface is readable anonymously.",
                            "Disable the UI outside development, or require authentication for it.");
                }
                return ConfigFinding.passing(getId(), getTitle(), uiEnabled
                        ? "Swagger UI is enabled and authentication is available."
                        : "Swagger UI is disabled.");
            }
        };
    }

    static ConfigCheck h2ConsoleDisabled() {
        return new AbstractCheck("h2-console-disabled", "H2 web console is disabled") {
            @Override
            public ConfigFinding evaluate(ConfigCheckContext context) {
                if (isEnabled(context, "spring.h2.console.enabled")) {
                    return ConfigFinding.failing(getId(), getTitle(), Severity.HIGH,
                            "The H2 console is enabled, exposing an interactive SQL shell over HTTP.",
                            "Set spring.h2.console.enabled=false outside local development.");
                }
                return ConfigFinding.passing(getId(), getTitle(), "The H2 console is disabled.");
            }
        };
    }

    private static boolean isEnabled(ConfigCheckContext context, String key) {
        return Boolean.parseBoolean(context.property(key));
    }

    private static int majorOf(String version) {
        return numericSegment(version, 0);
    }

    private static int minorOf(String version) {
        return numericSegment(version, 1);
    }

    private static int numericSegment(String version, int index) {
        String[] parts = version.split("[.\\-]");
        if (index >= parts.length) {
            return 0;
        }
        try {
            return Integer.parseInt(parts[index]);
        } catch (NumberFormatException e) {
            return 0;
        }
    }

    private abstract static class AbstractCheck implements ConfigCheck {
        private final String id;
        private final String title;

        AbstractCheck(String id, String title) {
            this.id = id;
            this.title = title;
        }

        @Override
        public String getId() {
            return id;
        }

        String getTitle() {
            return title;
        }
    }
}
